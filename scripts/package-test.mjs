import assert from 'node:assert/strict';
import { readFile, access, readdir } from 'node:fs/promises';
import { gzipSync } from 'node:zlib';
const pkg = JSON.parse(await readFile(new URL('../package.json', import.meta.url), 'utf8'));
assert.equal(pkg.type, 'module');
assert.equal(Object.keys(pkg.dependencies ?? {}).length, 0);
assert.equal(typeof globalThis.document, 'undefined');
const api = await import('a11y-toast');
const { docs } = await import('a11y-toast/docs');
const { createProgressAddon } = await import('a11y-toast/addons/progress');
const { trackToastPromise } = await import('a11y-toast/addons/promise');
for (const name of ['A11yToast', 'createToast', 'initToastAll', 'addToastEventListener']) assert.equal(typeof api[name], 'function');
assert.deepEqual(api.initToastAll(), []);
assert(Object.isFrozen(api.TOAST_EVENTS));
assert.equal(docs.slug, 'a11y-toast');
assert.equal(typeof createProgressAddon, 'function');
assert.equal(typeof trackToastPromise, 'function');
for (const name of ['index.js', 'index.d.ts', 'docs.js', 'docs.d.ts', 'styles.css', 'addons/progress.js', 'addons/progress.d.ts', 'addons/progress.css', 'addons/promise.js', 'addons/promise.d.ts']) await access(new URL(`../dist/${name}`, import.meta.url));
const files = await readdir(new URL('../dist/', import.meta.url));
let javascript = '';
for (const name of files.filter(name => name.endsWith('.js') && name !== 'docs.js')) javascript += await readFile(new URL(`../dist/${name}`, import.meta.url), 'utf8');
const css = await readFile(new URL('../dist/styles.css', import.meta.url), 'utf8');
const progressCss = await readFile(new URL('../dist/addons/progress.css', import.meta.url), 'utf8');
assert(progressCss.includes('prefers-reduced-motion') && progressCss.includes('aria') === false);
assert(css.includes('--a11y-toast-') && css.includes('--_') && css.includes('prefers-reduced-motion'));
assert(!javascript.includes('innerHTML'));
console.log('PASS: ESM exports, DOM-free import, explicit initialization, docs entry, declarations, stylesheet, zero runtime dependencies, safe text rendering.');
console.log(`Portable runtime modules: ${Buffer.byteLength(javascript)} bytes raw / ${gzipSync(javascript).length} bytes gzip (combined estimate; not a bundled transfer measurement).`);
console.log(`Stylesheet: ${Buffer.byteLength(css)} bytes raw / ${gzipSync(css).length} bytes gzip.`);
